"""Small structural contracts over existing Kalends implementations.

These document the compatibility boundary; they do not introduce another state
projection, event format, scheduler or provider transport.
"""
from __future__ import annotations

from typing import Any, Iterable, Mapping, Protocol


class World(Protocol):
    ledger: Any
    state: Any
    economy: Any
    clock: Any

    @property
    def minute(self) -> int: ...
    def on_task(self, task: dict) -> None: ...
    def fidelity_state(self) -> dict: ...


class AgentMind(Protocol):
    def observe(self, episode: Any) -> bool: ...
    def cycle(self, episodes: Iterable, goals: Iterable, options: Iterable,
              own_resources: Mapping, now: int) -> dict: ...
    def evaluate(self, action_id: str, outcome: str, *, now: int,
                 evidence_ids: Iterable = (), detail: str | None = None) -> dict: ...
    def retained_event_ids(self) -> Iterable[int]: ...
    def to_dict(self) -> dict: ...


class TimeEngine(Protocol):
    def advance(self, target: int, *, mode: str = "compress",
                strategy: str = "exact", coarse: int = 60) -> dict: ...
    def montage(self, events: Iterable, allowed_event_ids: set[int],
                *, limit: int = 8) -> list[dict]: ...


class Experience(Protocol):
    spec: Any
    world: World
    commands: list[dict]
    def commit(self, operation: str, data: dict) -> dict: ...
    def snapshot(self, *, operator: bool = False) -> dict: ...
    def save(self) -> None: ...
    def fork(self, command_index: int) -> dict: ...
    def debrief(self) -> dict: ...


class ExperienceCompiler(Protocol):
    def validate(self, value: Mapping | Any) -> Any: ...
    def compile(self, value: Any, **kwargs: Any) -> Experience: ...


class WorldInspector(Protocol):
    def events(self, *, operator: bool = False) -> list[dict]: ...
    def trace(self, event_id: int, *, operator: bool = False) -> dict: ...
    def snapshot(self, *, operator: bool = False) -> dict: ...
